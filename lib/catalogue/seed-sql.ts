import type { Item } from "@/types/parts";
import { itemToRow, listingToRow } from "./rows";
import { sortListings } from "./listings";

/**
 * Writes supabase/seed.sql from the JSON catalogue (Phase 16b). Regenerate with
 * `npm run db:seed-sql`; supabase/seed.test.ts fails while the committed file is
 * out of date, and checks that running it gives exactly the JSON's catalogue.
 */

const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const val = (v: unknown): string =>
  v === null || v === undefined
    ? "null"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : q(String(v));

const ITEM_COLS = [
  "category",
  "brand",
  "name",
  "tier",
  "price_idr",
  "dims",
  "specs",
  "model_id",
  "active",
  "position",
] as const;

export function seedSql(items: Item[], estimatesAsOf: string): string {
  const positions = new Map<string, number>();
  const rows = items.map((item) => {
    const n = positions.get(item.category) ?? 0;
    positions.set(item.category, n + 1);
    return itemToRow(item, n);
  });
  const listings = items.flatMap((i) =>
    sortListings(i.listings ?? []).map((l) => listingToRow(i.id, l)),
  );
  const ids = items.map((i) => q(i.id));

  const itemValues = rows
    .map(
      (r) =>
        `  (${[
          q(r.id),
          q(r.category),
          q(r.brand),
          q(r.name),
          q(r.tier),
          r.price_idr,
          r.dims ? json(r.dims) : "null",
          json(r.specs),
          val(r.model_id),
          r.active,
          r.position,
        ].join(", ")})`,
    )
    .join(",\n");

  const listingValues = listings
    .map(
      (l) =>
        `  (${[q(l.item_id), q(l.marketplace), q(l.url), l.price_idr, `${q(l.checked_at)}::date`].join(", ")})`,
    )
    .join(",\n");

  const distinct = (table: string, cols: readonly string[]) =>
    `(${cols.map((c) => `${table}.${c}`).join(", ")})\n  is distinct from (${cols.map((c) => `excluded.${c}`).join(", ")})`;

  return `-- CoreSpec catalogue seed (Phase 16b). GENERATED by \`npm run db:seed-sql\`
-- from data/parts, data/setup and data/meta.json: edit those, not this file.
--
-- ${items.length} items, ${listings.length} checked listings, and "estimates as of" ${estimatesAsOf}.
--
-- How to run: Supabase dashboard → SQL Editor → paste this whole file → Run,
-- after the migrations in supabase/migrations/.
--
-- Safe to run again (idempotent): it only changes rows that differ from the
-- JSON, so a second run changes nothing and writes nothing to the audit log.
-- Running it again also RESETS these items to the JSON: admin edits to them
-- (prices, listings, deactivated items) are put back as the JSON has them.
-- Items that only the database has are left alone.

begin;

insert into public.items (id, ${ITEM_COLS.join(", ")}) values
${itemValues}
on conflict (id) do update set
${ITEM_COLS.map((c) => `  ${c} = excluded.${c}`).join(",\n")}
where ${distinct("public.items", ITEM_COLS)};

-- Listings of these items that the JSON doesn't have.
delete from public.listings
where item_id in (
${chunk(ids, 6)}
)${
    listings.length
      ? `
  and (item_id, url) not in (
${listings.map((l) => `    (${q(l.item_id)}, ${q(l.url)})`).join(",\n")}
  )`
      : ""
  };
${
  listings.length
    ? `
insert into public.listings (item_id, marketplace, url, price_idr, checked_at) values
${listingValues}
on conflict (item_id, url) do update set
  marketplace = excluded.marketplace,
  price_idr = excluded.price_idr,
  checked_at = excluded.checked_at
where ${distinct("public.listings", ["marketplace", "price_idr", "checked_at"])};
`
    : ""
}
insert into public.site_settings (key, value) values
  ('estimates_as_of', ${json(estimatesAsOf)})
on conflict (key) do update set value = excluded.value
where public.site_settings.value is distinct from excluded.value;

commit;

select 'Seeded ${items.length} items and ${listings.length} listings' as result;
`;
}

function chunk(values: string[], perLine: number): string {
  const lines: string[] = [];
  for (let i = 0; i < values.length; i += perLine)
    lines.push(`  ${values.slice(i, i + perLine).join(", ")}`);
  return lines.join(",\n");
}
